#Pedir dos palabras al usuario y mostrarlas en pantalla concatenadas, es decir, una seguida 
#de la otra. ¿Cuáles son todas las maneras en que se pueden mostrar concatenadas en pantalla, 
#cadenas de caracteres? ¿Qué diferencia hay entre mostrarlas una seguida de otra en pantalla, 
#y en concatenarlas?

word_1 = input("Ingrese la primera palabra: ")    
word_2 = input("Ingrese la segunda palabra: ")
print("Palabras concatenadas:", word_1 + word_2)

# Concatenar las palabras significa unirlas para formar una sola cadena de caracteres.
